import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export interface InitOptions {
  /** Additional Flutter target directories to consider. */
  flutterDirs?: string[];
  /** Skip detection and write explicit values (used by tests). */
  entryFile?: string;
  exportName?: string;
}

export interface InitResult {
  configPath: string;
  config: {
    entry: string;
    exportName: string;
    adapter: 'trpc' | 'orpc';
    transformer: 'superjson' | 'json';
    dart: { outDir: string; packagePath?: string };
    policies: { unserializablePolicy: 'error' | 'warn-dynamic' | 'skip-procedure' };
  };
  detected: {
    tsconfig: string | null;
    routerCandidates: string[];
    flutterDirs: string[];
  };
}

const CONFIG_FILE = 'rpc-dart.config.ts';

/** Detects workspace shape and scaffolds rpc-dart.config.ts. Idempotent-guarded. */
export async function initWorkspace(workspaceDir: string, options: InitOptions = {}): Promise<InitResult> {
  const configPath = path.join(workspaceDir, CONFIG_FILE);
  if (existsSync(configPath)) {
    throw new Error(`${CONFIG_FILE} already exists at ${configPath} - refusing to overwrite`);
  }

  const detected: InitResult['detected'] = { tsconfig: null, routerCandidates: [], flutterDirs: [] };

  const tsconfigPath = path.join(workspaceDir, 'tsconfig.json');
  if (existsSync(tsconfigPath)) {
    detected.tsconfig = 'tsconfig.json';
  }

  const routerCandidates = findRouterCandidates(workspaceDir);
  detected.routerCandidates = routerCandidates;

  const flutterDirs = findFlutterDirs(workspaceDir, options.flutterDirs ?? []);
  detected.flutterDirs = flutterDirs;

  const entryFile =
    options.entryFile ??
    (routerCandidates.length > 0 ? path.relative(workspaceDir, routerCandidates[0]!) : 'src/trpc/router.ts');
  const entryText = existsSync(path.join(workspaceDir, entryFile))
    ? readFileSync(path.join(workspaceDir, entryFile), 'utf-8')
    : '';
  const exportName =
    options.exportName ??
    (/export\s+(?:const|type)\s+(appRouter|router|trpcRouter)\b/.exec(entryText)?.[1] ??
      /export\s+const\s+(\w+Router)\b/.exec(entryText)?.[1] ??
      'appRouter');

  const flutterTarget = flutterDirs[0];
  const adapter: 'trpc' | 'orpc' = /@orpc\/(contract|server)/.test(entryText)
    ? 'orpc'
    : 'trpc';
  const config: InitResult['config'] = {
    entry: entryFile,
    exportName,
    adapter,
    transformer: 'superjson',
    dart: {
      outDir: flutterTarget
        ? path.join(path.relative(workspaceDir, flutterTarget), 'lib/src/api')
        : 'lib/src/api',
      packagePath: flutterTarget ? path.relative(workspaceDir, flutterTarget) : undefined,
    },
    policies: { unserializablePolicy: 'error' },
  };

  writeFileSync(
    configPath,
    `import { defineConfig } from 'rpc-dart';

// Generated by rpc-dart init. Review the detected values below.
export default defineConfig({
  entry: ${JSON.stringify(config.entry)},
  exportName: ${JSON.stringify(config.exportName)},
  adapter: ${JSON.stringify(config.adapter)},
  transformer: ${JSON.stringify(config.transformer)},
  dart: {
    outDir: ${JSON.stringify(config.dart.outDir)},
    packagePath: ${config.dart.packagePath ? JSON.stringify(config.dart.packagePath) : 'undefined'},
  },
  policies: {
    unserializablePolicy: ${JSON.stringify(config.policies.unserializablePolicy)},
  },
});
`,
  );

  return { configPath, config, detected };
}

function findRouterCandidates(workspaceDir: string): string[] {
  const candidates: string[] = [];
  const scan = (dir: string, depth: number): void => {
    if (depth > 4 || candidates.length >= 5) return;
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        scan(full, depth + 1);
      } else if (
        /(^|\/)(router|trpc|app)\.tsx?$/.test(entry.name) ||
        entry.name.endsWith('Router.ts')
      ) {
        try {
          const text = readFileSync(full, 'utf-8');
          if (text.includes('initTRPC') || /@orpc\/(contract|server)/.test(text)) {
            candidates.push(full);
          }
        } catch {
          continue;
        }
      }
    }
  };
  scan(workspaceDir, 0);
  return candidates;
}

function findFlutterDirs(workspaceDir: string, extra: string[]): string[] {
  const found: string[] = [];
  for (const dir of [...readdirSafe(workspaceDir).map((n) => path.join(workspaceDir, n)), ...extra]) {
    if (existsSync(path.join(dir, 'pubspec.yaml'))) {
      found.push(dir);
    }
  }
  return found;
}

function readdirSafe(dir: string): string[] {
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && e.name !== 'node_modules' && !e.name.startsWith('.'))
      .map((e) => e.name);
  } catch {
    return [];
  }
}
